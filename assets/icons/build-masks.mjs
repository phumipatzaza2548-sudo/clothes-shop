/**
 * Regenerate the icon mask block in style.css.
 *
 * เปิดไฟล์เว็บผ่าน file:// แล้ว Chrome ไม่ยอมโหลด SVG ภายนอกมาใช้กับ CSS mask
 * (CORS: origin null) จึงฝัง SVG เป็น data URI ไว้ใน style.css
 *
 * วิธีใช้: node assets/icons/build-masks.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const cssPath = path.join(root, 'style.css');

const icons = {
    'ui-icon-sun': 'ui/sun.svg',
    'ui-icon-moon': 'ui/moon.svg',
    'ui-icon-cart': 'ui/cart.svg',
    'ui-icon-logout': 'ui/logout.svg',
    'ui-icon-truck': 'ui/truck.svg',
    'ui-icon-shield-check': 'ui/shield-check.svg',
    'ui-icon-size-exchange': 'ui/size-exchange.svg',
    'ui-icon-map-pin': 'ui/map-pin.svg',
    'ui-icon-phone': 'ui/phone.svg',
    'ui-icon-chevron-right': 'ui/chevron-right.svg',
    'ui-icon-facebook': 'social/facebook.svg',
    'ui-icon-instagram': 'social/instagram.svg',
    'ui-icon-tiktok': 'social/tiktok.svg',
    'ui-icon-line': 'social/line.svg'
};

const lines = Object.entries(icons).map(([className, file]) => {
    const svg = fs.readFileSync(path.join(here, file));
    const base64 = svg.toString('base64');
    return `.${className} { --ui-icon: url("data:image/svg+xml;base64,${base64}"); }`;
});

const start = '/* ICON-MASKS:START (generated by assets/icons/build-masks.mjs) */';
const end = '/* ICON-MASKS:END */';
const block = `${start}\n${lines.join('\n')}\n${end}`;

let css = fs.readFileSync(cssPath, 'utf8');
const pattern = new RegExp(`${start.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${end.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`);

if (!pattern.test(css)) {
    throw new Error('ไม่พบบล็อก ICON-MASKS ใน style.css');
}

css = css.replace(pattern, block);
fs.writeFileSync(cssPath, css, 'utf8');
console.log(`อัปเดตไอคอน ${lines.length} รายการใน style.css`);
